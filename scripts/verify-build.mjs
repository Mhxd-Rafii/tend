import { existsSync, readFileSync, readdirSync, statSync } from 'node:fs'
import { resolve, join } from 'node:path'
import assert from 'node:assert/strict'
const root = resolve('dist')
const files = directory => readdirSync(directory).flatMap(file => statSync(join(directory, file)).isDirectory() ? files(join(directory, file)) : [join(directory, file)])
assert(existsSync(root), 'Run npm run build first')
for (const file of ['index.html', 'sw.js', 'manifest.webmanifest', 'favicon.svg', 'icon-192.png', 'icon-512.png', 'apple-touch-icon.png']) assert(existsSync(join(root, file)), `Missing deploy artifact: ${file}`)
const manifest = JSON.parse(readFileSync(join(root, 'manifest.webmanifest'), 'utf8'))
for (const icon of manifest.icons) assert(existsSync(join(root, icon.src)), `Missing manifest icon: ${icon.src}`)
const html = readFileSync(join(root, 'index.html'), 'utf8')
assert(html.includes('Tend'), 'Starter title was not replaced')
for (const match of html.matchAll(/(?:src|href)="(\/[^"?#]+)"/g)) assert(existsSync(join(root, match[1])), `Missing HTML asset: ${match[1]}`)
const sw = readFileSync(join(root, 'sw.js'), 'utf8')
const precached = [...sw.matchAll(/url:"([^"]+)"/g)].map(match => match[1])
assert(precached.length > 15, 'Service worker should precache the complete application')
for (const file of precached) assert(existsSync(join(root, file)), `Missing precache asset: ${file}`)
for (const page of ['dashboard', 'calendar', 'activity-log', 'habits', 'gym', 'suggestions', 'settings', 'reports']) assert(precached.some(file => file.includes(`${page}-`)), `Offline cache missing ${page} page`)
const vercel = JSON.parse(readFileSync('vercel.json', 'utf8'))
assert(vercel.rewrites.some(rule => rule.destination === '/api'), 'Vercel API rewrite missing')
assert(vercel.rewrites.some(rule => rule.destination === '/index.html'), 'Vercel SPA fallback missing')
assert(vercel.headers.some(rule => rule.headers.some(header => header.key === 'Content-Security-Policy')), 'Security headers missing')
assert(existsSync('api/index.ts'), 'Vercel function entry missing')
assert(sw.includes('api'), 'API paths must be excluded from the navigation fallback')
console.log(`Verified ${files(root).length} frontend files, ${precached.length} cached resources, eight routes, PWA icons, Vercel API/SPA routing, and headers.`)
